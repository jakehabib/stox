/**
 * A bigger pool alone does not fix duplicate names — the birthday paradox does
 * not care how polite your odds look. With 200 first names and 240 surnames
 * there are 48,000 combinations, but a league carries roughly 1,700 players on
 * rosters plus a 400-deep class every year, and drawing 2,000 names from
 * 48,000 independently still yields around forty collisions. That is how a
 * 53-man roster ended up with two men both called Reggie Hollis.
 *
 * So the pool expansion is for *variety* (before this, sixty surnames across
 * 1,700 players meant every name recurred ~28 times league-wide, which is why
 * one roster fielded four different Northcutts), and this registry is for
 * *correctness*. Generation consults it and re-rolls on a hit.
 */
export class NameRegistry {
  private taken = new Set<string>();

  constructor(existing: Iterable<string> = []) {
    for (const n of existing) this.taken.add(n.toLowerCase());
  }

  has(full: string): boolean {
    return this.taken.has(full.toLowerCase());
  }

  add(full: string): void {
    this.taken.add(full.toLowerCase());
  }

  get size(): number {
    return this.taken.size;
  }
}

/** Generational suffixes, in the order a family would actually use them. */
const SUFFIXES = ['Jr.', 'II', 'III', 'IV'];

/**
 * Draws a full name that no one in this league already has.
 *
 * Re-rolls first, because a fresh combination is always the nicest outcome.
 * If the caller has genuinely exhausted the space (or is very unlucky), falls
 * back to a generational suffix — "Marcus Whitfield Jr." reads as a real
 * football name in a way that "Marcus Whitfield 2" never would, and the NFL is
 * full of them. Only if every suffix is also taken does it give up and return
 * the duplicate rather than loop forever.
 *
 * `rng` must be the caller's seeded Rng so generation stays deterministic.
 */
export function pickUniqueName(
  rng: { pick<T>(arr: readonly T[]): T },
  registry: NameRegistry,
): { firstName: string; lastName: string } {
  for (let attempt = 0; attempt < 40; attempt++) {
    const firstName = rng.pick(FIRST_NAMES);
    const lastName = rng.pick(LAST_NAMES);
    const full = `${firstName} ${lastName}`;
    if (!registry.has(full)) {
      registry.add(full);
      return { firstName, lastName };
    }
  }

  const firstName = rng.pick(FIRST_NAMES);
  const base = rng.pick(LAST_NAMES);
  for (const suffix of SUFFIXES) {
    const lastName = `${base} ${suffix}`;
    const full = `${firstName} ${lastName}`;
    if (!registry.has(full)) {
      registry.add(full);
      return { firstName, lastName };
    }
  }

  registry.add(`${firstName} ${base}`);
  return { firstName, lastName: base };
}
